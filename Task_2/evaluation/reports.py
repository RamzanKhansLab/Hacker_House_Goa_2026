from __future__ import annotations

from pathlib import Path


def render_latency_report(summary: dict[str, dict[str, float]], quality: dict[str, float], query_count: int) -> str:
    lines = [
        "# Latency Benchmark Report",
        "",
        f"Measured queries: {query_count}",
        "",
        "## Pipeline latency (milliseconds)",
        "",
        "| Stage | P50 | P70 | P90 | P95 | P99 | P100 |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for stage, values in summary.items():
        pretty = stage.replace("_ms", "").replace("_", " ")
        lines.append("| " + pretty + " | " + " | ".join(str(values[f"p{x}"]) for x in (50, 70, 90, 95, 99, 100)) + " |")
    lines.extend(["", "## Retrieval quality", ""])
    lines.extend(f"- {key}: {value}" for key, value in quality.items())
    lines.extend(["", "Numbers in this file are generated by `python -m evaluation.benchmark`; do not reuse them across changed indexes or environments."])
    return "\n".join(lines) + "\n"


def ensure_output_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)
